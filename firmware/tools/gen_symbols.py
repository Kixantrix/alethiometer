#!/usr/bin/env python3
"""Regenerate firmware/src/symbols.h from js/symbols.js (the single source of truth).

Usage (from the repo root or anywhere):  python firmware/tools/gen_symbols.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "js" / "symbols.js"
TARGET = ROOT / "firmware" / "src" / "symbols.h"
EXPECTED_COUNT = 36


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")
    names = re.findall(r"name:\s*'((?:[^'\\]|\\.)*)'", text)
    if len(names) != EXPECTED_COUNT:
        print(f"expected {EXPECTED_COUNT} symbols in {SOURCE}, found {len(names)}", file=sys.stderr)
        return 1
    rows = "\n".join(f'    "{n.replace(chr(92), "")}",  // {i:2d}  {i * 10:3d} deg'
                     for i, n in enumerate(names))
    TARGET.write_text(f"""// GENERATED by firmware/tools/gen_symbols.py from js/symbols.js - do not edit.
// The 36 alethiometer symbols in wheel order: index i sits i*10 deg clockwise from 12 o'clock.
#pragma once

#include <stdint.h>

constexpr int SYMBOL_COUNT = {len(names)};
constexpr float SYMBOL_STEP_DEG = 360.0f / SYMBOL_COUNT;

static const char *const SYMBOL_NAMES[SYMBOL_COUNT] = {{
{rows}
}};

constexpr int SYMBOL_HOURGLASS = 0;
constexpr int SYMBOL_MOON = 10;
""", encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(names)} symbols)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
