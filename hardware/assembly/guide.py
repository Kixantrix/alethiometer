# Parts and selectors
@dataclass(frozen=True)
class Inst:
    part: str
    index: int

    @property
    def key(self) -> str:
        return f"{self.part}#{self.index}"


def design_parts():
    import design as D
    return D.all_parts() + D.tooling()


class Catalogue:
    def __init__(self, parts):
        self.parts = {p.name: p for p in parts}
        self.order = [p.name for p in parts]
        self.tools = {p.name for p in parts if p.group == "tools"}
        self._boxes: dict[str, tuple] = {}

    def box(self, key: str) -> tuple:
        """Installed bounding box of one instance: (xmin, ymin, zmin, xmax, ymax, zmax)."""
        if key not in self._boxes:
            name, i = key.split("#")
            b = self.parts[name].placed()[int(i)].BoundingBox()
            self._boxes[key] = (b.xmin, b.ymin, b.zmin, b.xmax, b.ymax, b.zmax)
        return self._boxes[key]

    def anchor(self, key: str, where: str) -> list[float]:
        x0, y0, z0, x1, y1, z1 = self.box(key)
        c = [(x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2]
        axis, val = {"top": (2, z1), "bottom": (2, z0), "+x": (0, x1), "-x": (0, x0),
                     "+y": (1, y1), "-y": (1, y0), "center": (None, None)}[where]
        if axis is not None:
            c[axis] = val
        return [round(v, 3) for v in c]

    def select(self, sel) -> list[Inst]:
        if sel is None:
            return []
        if isinstance(sel, list):
            out: list[Inst] = []
            for s in sel:
                out += [i for i in self.select(s) if i not in out]
            return out
        sel = str(sel).strip()
        if sel == "all":
            return [Inst(n, i) for n in self.order if n not in self.tools for i in range(self.parts[n].qty)]
        name, _, idx = sel.partition("#")
        names = [n for n in self.order if fnmatch.fnmatchcase(n, name)]
        if not names:
            raise ValueError(f"selector {sel!r} matches no part")
        out = []
        for n in names:
            q = self.parts[n].qty
            if idx:
                ids = [int(v) for v in idx.split(",")]
                if any(not 0 <= v < q for v in ids):
                    raise ValueError(f"selector {sel!r}: {n} has {q} instance(s)")
            else:
                ids = range(q)
            out += [Inst(n, i) for i in ids]
        return out


