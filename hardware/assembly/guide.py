ANCHORS = {"top", "bottom", "center", "+x", "-x", "+y", "-y"}
VIEWS = {"iso", "top", "side", "under", "back", "front", "right", "left"}
AXES = {"x": [1.0, 0.0, 0.0], "y": [0.0, 1.0, 0.0], "z": [0.0, 0.0, 1.0]}
