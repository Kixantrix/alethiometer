"""Assembly guide: one source (steps.yaml) for the animated viewer guide and ASSEMBLY.md.

    python hardware/assembly/guide.py            # validate; write ASSEMBLY.md, FINDINGS.md, viewer JSON
    python hardware/assembly/guide.py --check    # validate only; fail if the generated docs are stale

steps.yaml describes every step as motions of CAD part instances. A motion moves instances
from a pose to a pose (default: their installed place), optionally spinning, fading or
removing them afterwards. A pose is a translation `t` (or `up: dz`) applied after an optional
rotation `rot` about a pivot. Poses are deltas from each instance's installed placement, in
the CAD frame (mm, Z up). This module is the reference for those semantics: it replays the
whole guide into each step's start state and per-instance tracks, which the viewer only
interpolates, and check_paths.py sweeps for collisions.
"""
