# Replay
@dataclass
class Segment:
    t0: float
    t1: float
    a: dict
    b: dict
    spin: float = 0.0
    fade: str | None = None
    driver: dict | None = None
    nocheck: bool = False
    remove: bool = False
    pivot: str | None = None        # spin about this instance's centre axis instead of each part's own

    def at(self, t: float) -> dict:
        if t <= self.t0:
            return self.a
        if t >= self.t1:
            return self.b
        return lerp_pose(self.a, self.b, ease((t - self.t0) / (self.t1 - self.t0)))


MOTION_KEYS = {"parts", "from", "to", "by", "dur", "at", "with", "stagger", "spin", "pivot", "remove", "fade",
               "driver", "lid", "note", "nocheck"}


def step_timeline(step: dict, cat: Catalogue, state: dict, lid: float, where: str):
    """Replay one step's motions. Returns (tracks, end state, end lid, lid track, duration)."""
    tracks: dict[str, list[Segment]] = {}
    removed: set[str] = set()
    t_prev0 = t_prev1 = 0.0
    lid_track = None
    for k, mo in enumerate(step.get("motions") or []):
        ctx = f"{where} motion {k + 1}"
        unknown = set(mo) - MOTION_KEYS
        if unknown:
            raise ValueError(f"{ctx}: unknown keys {sorted(unknown)}")
        dur = float(mo.get("dur", LID_DUR if "lid" in mo else DEFAULT_DUR))
        if "at" in mo:
            t0 = float(mo["at"])
        elif mo.get("with") == "prev":
            t0 = t_prev0
        else:
            t0 = t_prev1
        if "lid" in mo:
            if "parts" in mo:
                raise ValueError(f"{ctx}: a lid motion has no parts")
            lid_track = dict(a=lid, b=float(mo["lid"]), t0=t0, t1=t0 + dur)
            lid = float(mo["lid"])
            t_prev0, t_prev1 = t0, t0 + dur
            continue
        insts = cat.select(mo.get("parts"))
        if not insts:
            raise ValueError(f"{ctx}: no parts")
        if "from" in mo and "by" in mo:
            raise ValueError(f"{ctx}: use `from` or `by`, not both")
        if mo.get("fade") not in (None, "in", "out"):
            raise ValueError(f"{ctx}: fade must be in or out")
        pivot = None
        if "pivot" in mo:
            piv = cat.select(mo["pivot"])
            if len(piv) != 1 or not mo.get("spin"):
                raise ValueError(f"{ctx}: pivot must select exactly one part, on a spinning motion")
            pivot = piv[0].key
        stagger = float(mo.get("stagger", 0.0))
        end = t0
        for n, inst in enumerate(insts):
            cur = state.get(inst.key)
            try:
                if "from" in mo:
                    a = pose(mo["from"])
                elif cur and cur["shown"]:
                    a = copy.deepcopy(cur["pose"])
                else:
                    a = None
                if "by" in mo:
                    if a is None:
                        raise ValueError(f"{inst.key} is not shown yet; `by` needs a current pose")
                    b = compose_by(pose(mo["by"]), a)
                elif "to" in mo or a is None or "from" in mo:
                    b = pose(mo.get("to"))
                else:
                    b = copy.deepcopy(a)                    # e.g. a spin or fade in place
                if a is None:
                    a = b                                   # appears in place
                check_pair(a, b)
            except ValueError as e:
                raise ValueError(f"{ctx}: {e}") from None
            s0 = t0 + n * stagger
            gone = bool(mo.get("remove")) or mo.get("fade") == "out"
            tracks.setdefault(inst.key, []).append(Segment(
                s0, s0 + dur, a, b, float(mo.get("spin", 0.0)), mo.get("fade"), mo.get("driver"),
                bool(mo.get("nocheck")), gone, pivot))
            state[inst.key] = dict(pose=b, shown=True)
            if gone:
                removed.add(inst.key)
            else:
                removed.discard(inst.key)
            end = max(end, s0 + dur)
        t_prev0, t_prev1 = t0, end
    duration = max([0.6] + [s.t1 for segs in tracks.values() for s in segs]
                   + ([lid_track["t1"]] if lid_track else []))
    for key in removed:
        state[key]["shown"] = False
    return tracks, state, lid, lid_track, duration


def replay(guide: dict, cat: Catalogue) -> list[dict]:
    """Per step: start state, tracks, lid and visibility filters, in guide order."""
    state: dict[str, dict] = {}
    lid = float(guide.get("lid_start", 0.0))
    out = []
    for sec in guide["sections"]:
        for step in sec.get("steps") or []:
            start = copy.deepcopy(state)
            lid0 = lid
            tracks, state, lid, lid_track, dur = step_timeline(step, cat, state, lid, f"step {step.get('id')}")
            only = step.get("only")
            out.append(dict(section=sec, step=step, start=start, tracks=tracks, lid0=lid0,
                            lid_track=lid_track, lid1=lid, duration=dur,
                            only={i.key for i in cat.select(only)} if only else None,
                            hide={i.key for i in cat.select(step.get("hide"))}))
    return out


def visible_keys(r: dict) -> set[str]:
    """Instances drawn during a step: everything placed so far plus what moves, filtered by only/hide."""
    keys = {k for k, v in r["start"].items() if v["shown"]} | set(r["tracks"])
    if r["only"] is not None:
        keys = {k for k in keys if k in r["only"] or k in r["tracks"]}
    return keys - (r["hide"] - set(r["tracks"]))


def present(r: dict, key: str, t: float) -> bool:
    """Is the instance physically there at time t? A part brought in during the step arrives when its
    first motion starts; a part removed leaves when that motion ends."""
    segs = r["tracks"].get(key)
    if not segs:
        return True
    shown = key in r["start"] and r["start"][key]["shown"]
    if not shown and t <= segs[0].t0 + 1e-6:
        return False
    for s in segs:
        if s.remove and t > s.t1 and not any(o.t0 >= s.t1 for o in segs if o is not s):
            return False
    return True


def lid_at(r: dict, t: float) -> float:
    lt = r["lid_track"]
    if not lt or t <= lt["t0"]:
        return r["lid0"] if not lt else lt["a"]
    if t >= lt["t1"]:
        return lt["b"]
    return lt["a"] + (lt["b"] - lt["a"]) * ease((t - lt["t0"]) / (lt["t1"] - lt["t0"]))


def pose_at(r: dict, key: str, t: float) -> dict:
    segs = r["tracks"].get(key)
    if not segs:
        return r["start"][key]["pose"]
    seg = segs[0]
    for s in segs:
        if t >= s.t0:
            seg = s
    return seg.at(t)


