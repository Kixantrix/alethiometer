# Outputs
def step_numbers(guide: dict):
    for sec in guide["sections"]:
        for n, step in enumerate(sec.get("steps") or [], 1):
            yield sec, step, f"{sec['number']}.{n}"


def _bullets(label: str, items: list[str]) -> list[str]:
    if not items:
        return []
    if len(items) == 1:
        return [f"*{label}:* {items[0].strip()}", ""]
    return [f"*{label}:*", ""] + [f"- {i.strip()}" for i in items] + [""]


def write_markdown(guide: dict) -> tuple[str, str]:
    markers = guide.get("markers") or {}
    findings = {f["id"]: f for f in guide.get("findings") or []}
    lines = [GENERATED, "", f"# {guide.get('title', 'Assembly')}", "", guide.get("preface", "").strip(), ""]
    for sec in guide["sections"]:
        lines += [f"## {sec['number']}. {sec['title']}", ""]
        if sec.get("intro"):
            lines += [sec["intro"].strip(), ""]
        for n, step in enumerate(sec.get("steps") or [], 1):
            if step.get("md") is False:
                continue
            lines += [f"### {sec['number']}.{n} {'Test: ' if step.get('test') else ''}{step['title']}", ""]
            if step.get("text"):
                lines += [step["text"].strip(), ""]
            applied = []
            for a in step.get("apply") or []:
                label = markers[a["what"]]["label"]
                applied.append(f"{label}: {a['note']}" if a.get("note") else label)
            lines += _bullets("Apply", list(dict.fromkeys(applied)))
            lines += _bullets("Tools", step.get("tools") or [])
            lines += _bullets("Check", step.get("checks") or [])
            lines += _bullets("If it fails", step.get("fixes") or [])
            lines += _bullets("Caution", step.get("cautions") or [])
            refs = [f"[{f}: {findings[f]['title']}](assembly/FINDINGS.md#{f.lower()})"
                    for f in step.get("findings") or []]
            lines += _bullets("Design review", refs)
        for sub in sec.get("subsections") or []:
            lines += [f"### {sub['title']}", "", sub["text"].strip(), ""]
    if guide.get("troubleshooting"):
        lines += ["## Troubleshooting", "", guide["troubleshooting"].strip(), ""]
    md = re.sub(r"\n{3,}", "\n\n", "\n".join(lines).rstrip() + "\n")

    order = {"high": 0, "medium": 1, "low": 2}
    where: dict[str, list[str]] = {}
    for sec, step, num in step_numbers(guide):
        for f in step.get("findings") or []:
            where.setdefault(f, []).append(f"{num} {step['title']}")
    items = sorted(findings.values(), key=lambda f: (order.get(f["impact"], 9), f["id"]))
    fl = [GENERATED, "", "# Design review: assembly and parting-out findings", "",
          (guide.get("findings_intro") or "").strip(), "",
          "| ID | Impact | Status | Finding | Steps |", "|---|---|---|---|---|"]
    for f in items:
        fl.append(f"| [{f['id']}](#{f['id'].lower()}) | {f['impact']} | {f['status']} | {f['title']} | "
                  + "; ".join(where.get(f["id"], [])) + " |")
    fl.append("")
    for f in items:
        fl += [f"## {f['id']}", "", f"**{f['title']}**", "",
               f"Impact: {f['impact']} · Status: {f['status']}" + (f" · Area: {f['area']}" if f.get("area") else ""),
               "", "**Observation.** " + f["observation"].strip(), "",
               "**Recommendation.** " + f["recommendation"].strip(), ""]
        if f.get("resolution"):
            fl += ["**Resolution.** " + f["resolution"].strip(), ""]
        if where.get(f["id"]):
            fl += ["Seen in: " + "; ".join(where[f["id"]]), ""]
    findings_md = re.sub(r"\n{3,}", "\n\n", "\n".join(fl).rstrip() + "\n")
    return md, findings_md


def _seg_json(s: Segment) -> dict:
    return dict(t0=round(s.t0, 3), t1=round(s.t1, 3), a=s.a, b=s.b, spin=s.spin, fade=s.fade,
                driver=s.driver, remove=s.remove, pivot=s.pivot)


def viewer_json(guide: dict, cat: Catalogue, runs: list[dict]) -> dict:
    steps = []
    for r, (sec, step, num) in zip(runs, step_numbers(guide)):
        vis = visible_keys(r)
        steps.append(dict(
            id=step["id"], num=num, section=sec["number"], title=step["title"],
            text=(step.get("text") or "").strip(), view=step.get("view"),
            frame=[i.key for i in cat.select(step.get("frame"))],
            visible=sorted(vis),
            start={k: v["pose"] for k, v in r["start"].items() if v["shown"] and k in vis},
            tracks={k: [_seg_json(s) for s in segs] for k, segs in r["tracks"].items() if k in vis},
            duration=round(r["duration"], 3),
            lid=dict(a=r["lid0"], b=r["lid1"], t0=r["lid_track"]["t0"] if r["lid_track"] else 0.0,
                     t1=r["lid_track"]["t1"] if r["lid_track"] else 0.0),
            apply=[dict(what=a["what"], note=a.get("note", ""), time=float(a.get("time", 0.0)),
                        offset=a.get("offset", [0, 0, 0]),
                        at=[dict(key=i.key, p=cat.anchor(i.key, a.get("anchor", "center")))
                            for i in cat.select(a["at"])])
                   for a in step.get("apply") or []],
            tools=step.get("tools") or [], checks=step.get("checks") or [], fixes=step.get("fixes") or [],
            test=bool(step.get("test")),
            cautions=step.get("cautions") or [], findings=step.get("findings") or [],
        ))
    return dict(
        title=guide.get("title", "Assembly"),
        sections=[dict(number=s["number"], title=s["title"], intro=(s.get("intro") or "").strip())
                  for s in guide["sections"]],
        markers=guide.get("markers") or {},
        findings={f["id"]: f for f in guide.get("findings") or []},
        steps=steps,
    )


def load(path: Path = STEPS) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def write_viewer_json(parts=None) -> bool:
    """Validate the guide and write only the viewer's assets/assembly.json (used by export_viewer.py)."""
    guide = load()
    cat = Catalogue(parts if parts is not None else design_parts())
    errors = validate(guide, cat)
    if errors:
        print("warning: assembly guide not exported:\n  " + "\n  ".join(errors), flush=True)
        VIEWER_JSON.unlink(missing_ok=True)
        return False
    VIEWER_JSON.write_text(json.dumps(viewer_json(guide, cat, replay(guide, cat)), separators=(",", ":")),
                           encoding="utf-8")
    print(f"  assembly guide: {sum(len(s.get('steps') or []) for s in guide['sections'])} steps -> "
          f"{VIEWER_JSON.relative_to(HW)}", flush=True)
    return True


def build(check_only: bool = False, parts=None) -> int:
    guide = load()
    cat = Catalogue(parts if parts is not None else design_parts())
    errors = validate(guide, cat)
    if errors:
        print("assembly guide errors:\n  " + "\n  ".join(errors))
        return 1
    runs = replay(guide, cat)
    md, findings_md = write_markdown(guide)
    if check_only:
        stale = [p.name for p, text in ((ASSEMBLY_MD, md), (FINDINGS_MD, findings_md))
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("stale generated docs (run hardware/assembly/guide.py): " + ", ".join(stale))
            return 1
        print(f"assembly guide OK: {len(runs)} steps, {len(guide.get('findings') or [])} findings")
        return 0
    ASSEMBLY_MD.write_text(md, encoding="utf-8")
    FINDINGS_MD.write_text(findings_md, encoding="utf-8")
    wrote = [ASSEMBLY_MD.name, FINDINGS_MD.name]
    if VIEWER_JSON.parent.exists():
        VIEWER_JSON.write_text(json.dumps(viewer_json(guide, cat, runs), separators=(",", ":")), encoding="utf-8")
        wrote.append(str(VIEWER_JSON.relative_to(HW)))
    total = sum(r["duration"] for r in runs)
    print(f"assembly guide: {len(runs)} steps, {total / 60:.1f} min of animation, "
          f"{len(guide.get('findings') or [])} findings -> {', '.join(wrote)}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate and verify the generated docs are current")
    return build(check_only=ap.parse_args().check)


if __name__ == "__main__":
    sys.exit(main())
