# Poses
def _axis(a) -> list[float]:
    if isinstance(a, str):
        sign = -1.0 if a.startswith("-") else 1.0
        return [sign * v for v in AXES[a.lstrip("+-")]]
    v = np.array(a, dtype=float)
    return (v / np.linalg.norm(v)).tolist()


def pose(spec) -> dict:
    """Normalise a YAML pose ({up}, {t}, {rot}) to {t: [x,y,z], rot: None | {axis, about, deg}}."""
    if spec is None or spec == "home":
        return dict(t=[0.0, 0.0, 0.0], rot=None)
    if not isinstance(spec, dict):
        raise ValueError(f"bad pose {spec!r}")
    unknown = set(spec) - {"t", "up", "rot"}
    if unknown:
        raise ValueError(f"unknown pose keys {sorted(unknown)}")
    t = [float(v) for v in spec.get("t", [0, 0, 0])]
    t[2] += float(spec.get("up", 0.0))
    rot = None
    if spec.get("rot"):
        r = spec["rot"]
        rot = dict(axis=_axis(r["axis"]), about=[float(v) for v in r.get("about", [0, 0, 0])],
                   deg=float(r["deg"]))
    return dict(t=t, rot=rot)


def _same_rot_frame(a, b) -> bool:
    return np.allclose(a["axis"], b["axis"]) and np.allclose(a["about"], b["about"])


def compose_by(by: dict, cur: dict) -> dict:
    """Apply a relative move after the current pose (translation adds; rotation must share axis+pivot)."""
    t = [a + b for a, b in zip(cur["t"], by["t"])]
    rot = cur["rot"]
    if by["rot"]:
        if rot and not _same_rot_frame(rot, by["rot"]):
            raise ValueError("`by` rotation must use the same axis and pivot as the current pose")
        if any(cur["t"]):
            raise ValueError("`by` rotation on a translated pose is ambiguous; use `to`")
        rot = dict(by["rot"], deg=(rot["deg"] if rot else 0.0) + by["rot"]["deg"])
    return dict(t=t, rot=rot)


def check_pair(a: dict, b: dict) -> None:
    if a["rot"] and b["rot"] and not _same_rot_frame(a["rot"], b["rot"]):
        raise ValueError("a motion's from/to rotations must share axis and pivot")


def lerp_pose(a: dict, b: dict, s: float) -> dict:
    t = [x + (y - x) * s for x, y in zip(a["t"], b["t"])]
    ra, rb = a["rot"], b["rot"]
    if not ra and not rb:
        return dict(t=t, rot=None)
    frame = ra or rb
    da, db = (ra["deg"] if ra else 0.0), (rb["deg"] if rb else 0.0)
    return dict(t=t, rot=dict(frame, deg=da + (db - da) * s))


def ease(s: float) -> float:
    """Cubic ease in/out; the viewer uses the same curve."""
    return 4 * s ** 3 if s < 0.5 else 1 - (-2 * s + 2) ** 3 / 2


def matrix(p: dict) -> np.ndarray:
    m = np.eye(4)
    if p["rot"] and p["rot"]["deg"]:
        u = np.array(p["rot"]["axis"])
        a = math.radians(p["rot"]["deg"])
        k = np.array([[0, -u[2], u[1]], [u[2], 0, -u[0]], [-u[1], u[0], 0]])
        r = np.eye(3) + math.sin(a) * k + (1 - math.cos(a)) * k @ k
        c = np.array(p["rot"]["about"])
        m[:3, :3] = r
        m[:3, 3] = c - r @ c
    m[:3, 3] += p["t"]
    return m


