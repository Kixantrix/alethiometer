# Validation
def validate(guide: dict, cat: Catalogue) -> list[str]:
    errors = []
    markers = guide.get("markers") or {}
    findings = {f["id"]: f for f in guide.get("findings") or []}
    ids = set()
    step_keys = {"id", "title", "text", "view", "only", "hide", "frame", "motions", "apply", "tools",
                 "checks", "fixes", "cautions", "findings", "md", "test"}
    for sec in guide["sections"]:
        for step in sec.get("steps") or []:
            sid = step.get("id")
            where = f"step {sid}"
            if not sid or not re.fullmatch(r"[a-z0-9][a-z0-9-]*", str(sid)):
                errors.append(f"{where}: id must be lower-case kebab-case")
            if sid in ids:
                errors.append(f"{where}: duplicate id")
            ids.add(sid)
            if not step.get("title"):
                errors.append(f"{where}: missing title")
            unknown = set(step) - step_keys
            if unknown:
                errors.append(f"{where}: unknown keys {sorted(unknown)}")
            for key in ("only", "hide", "frame"):
                try:
                    cat.select(step.get(key))
                except ValueError as e:
                    errors.append(f"{where} {key}: {e}")
            for a in step.get("apply") or []:
                if a.get("what") not in markers:
                    errors.append(f"{where}: apply marker {a.get('what')!r} not in markers")
                if a.get("anchor", "center") not in ANCHORS:
                    errors.append(f"{where}: anchor {a.get('anchor')!r} not one of {sorted(ANCHORS)}")
                try:
                    if not cat.select(a.get("at")):
                        errors.append(f"{where}: apply needs `at`")
                except ValueError as e:
                    errors.append(f"{where} apply: {e}")
            for f in step.get("findings") or []:
                if f not in findings:
                    errors.append(f"{where}: unknown finding {f}")
            view = step.get("view")
            if view is not None and not ((isinstance(view, list) and len(view) == 3) or view in VIEWS):
                errors.append(f"{where}: bad view {view!r}")
    try:
        runs = replay(guide, cat)
    except ValueError as e:
        return errors + [str(e)]
    used = {k.split("#")[0] for r in runs for k in r["tracks"]}
    missing = [n for n in cat.order if n not in used]
    if missing:
        errors.append("parts never shown in any step: " + ", ".join(missing))
    end = runs[-1]
    final = {k: v for k, v in end["start"].items()}
    for k, segs in end["tracks"].items():
        final[k] = dict(pose=segs[-1].b, shown=True)
    for key in (Inst(n, i).key for n in cat.order if n not in cat.tools for i in range(cat.parts[n].qty)):
        st = final.get(key)
        if not st or not st["shown"]:
            errors.append(f"{key} is not in the finished instrument")
        elif np.abs(matrix(st["pose"]) - np.eye(4)).max() > 1e-6:
            errors.append(f"{key} does not end at its installed place")
    for f in findings.values():
        for key in ("title", "impact", "observation", "recommendation", "status"):
            if not f.get(key):
                errors.append(f"finding {f.get('id')}: missing {key}")
    return errors


